const lazyImageObserver = new MutationObserver((records) => {
  records.forEach((record) => record.addedNodes.forEach((node) => {
    if (!(node instanceof Element)) return;
    const images = node.matches('img') ? [node] : Array.from(node.querySelectorAll('img'));
    images.forEach((image) => {
      image.decoding = 'async';
      if (!image.closest('.site-header, .hero, .history-hero') && image.fetchPriority !== 'high') image.loading = 'lazy';
    });
  }));
});
lazyImageObserver.observe(document.body, { childList: true, subtree: true });

